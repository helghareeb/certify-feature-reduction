"""Write `results/MANIFEST.sha256` over every tracked file under `results/`.

Exists as a script because it was regenerated by hand three times in one night and drifted
each time -- once shipping a manifest that failed on a fresh clone, which is the only place
a manifest is actually tested. Anything regenerated by hand more than twice belongs in a
file.

Covers TRACKED files only. A manifest listing gitignored artefacts cannot be verified from
a clone, which defeats its purpose.

    python scripts/make_results_manifest.py            # write it
    python scripts/make_results_manifest.py --check    # verify; non-zero exit on any mismatch
"""
from __future__ import annotations

import argparse
import hashlib
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "results" / "MANIFEST.sha256"


def entries() -> list[tuple[str, str]]:
    out = subprocess.run(["git", "ls-files", "results/"], cwd=ROOT,
                         capture_output=True, text=True).stdout.split()
    rows = []
    for f in sorted(out):
        if f == "results/MANIFEST.sha256":
            continue
        p = ROOT / f
        if not p.is_file():
            continue
        rows.append((hashlib.sha256(p.read_bytes()).hexdigest(), f[len("results/"):]))
    return rows


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    rows = entries()
    if a.check:
        if not MANIFEST.exists():
            print("FAIL: results/MANIFEST.sha256 does not exist")
            return 1
        have = {}
        for line in MANIFEST.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            h, _, name = line.partition("  ")
            have[name] = h
        want = {n: h for h, n in rows}
        missing = sorted(set(want) - set(have))
        extra = sorted(set(have) - set(want))
        bad = sorted(n for n in set(want) & set(have) if want[n] != have[n])
        if missing or extra or bad:
            print(f"FAIL: {len(bad)} changed, {len(missing)} unlisted, {len(extra)} stale")
            for n in (bad + missing + extra)[:12]:
                print("   ", n)
            return 1
        print(f"PASS: {len(rows)} tracked result file(s), all hashes current")
        return 0

    MANIFEST.write_text("\n".join(f"{h}  {n}" for h, n in rows) + "\n",
                        encoding="utf-8", newline="\n")
    print(f"wrote {MANIFEST.relative_to(ROOT)} over {len(rows)} tracked file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
