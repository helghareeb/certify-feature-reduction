"""Meta-analysis: when is aggressive feature reduction safe?

Across all datasets, relate the magnitude of the reliability harm (the AURC penalty at the most
aggressive budget) to intrinsic dataset properties -- feature redundancy, intrinsic dimensionality,
the sample-to-feature ratio, prevalence -- to derive a generalisable rule for when reduction is
benign versus damaging. Reads the canonical summary (R2); loads each dataset only to compute its
descriptors. Emits paper/meta_table.tex, paper/figures/meta_harm.pdf, and prints the rule.

    PYTHONPATH=src python experiments/meta_analysis.py
"""
from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy.stats import spearmanr
from sklearn.decomposition import PCA

from nsclinfs import data as dataload

PROPS = [("redundancy", "feature redundancy"), ("intrinsic_dim_frac", "intrinsic-dim fraction"),
         ("np_ratio", "sample:feature ratio"), ("prevalence", "outcome prevalence"),
         ("p", "feature count")]


def dataset_properties(name: str, calib_path: str = "config/calibration.json") -> dict:
    import json
    params = json.loads(Path(calib_path).read_text()).get("dataset_params", {}).get(name)
    X, y, _ = dataload.load(name, params=params)
    Xn = X.apply(pd.to_numeric, errors="coerce")
    Xf = Xn.fillna(Xn.median(numeric_only=True))
    sd = Xf.std(ddof=0).replace(0.0, 1.0)
    Xs = ((Xf - Xf.mean()) / sd).to_numpy()
    n, p = X.shape
    if p > 1:
        corr = np.corrcoef(Xs.T)
        iu = np.triu_indices(p, 1)
        redundancy = float(np.nanmean(np.abs(corr[iu])))
        cum = np.cumsum(PCA().fit(Xs).explained_variance_ratio_)
        k95 = int(np.searchsorted(cum, 0.95) + 1)
        intrinsic = k95 / p
    else:
        redundancy, intrinsic = 0.0, 1.0
    return {"dataset": name, "n": n, "p": p, "np_ratio": n / p,
            "prevalence": float(np.mean(y)), "redundancy": redundancy,
            "intrinsic_dim_frac": intrinsic}


def harm_by_dataset(summary_csv: str, outcome: str = "aurc") -> pd.Series:
    from nsclinfs.hashing import CALIB_HASH_KEY, assert_single_hash
    s = pd.read_csv(summary_csv, comment="#")
    if CALIB_HASH_KEY in s.columns:                    # R6: refuse a mixed-hash summary
        assert_single_hash(s[CALIB_HASH_KEY])
    if "budget_type" in s.columns:                     # keep the harm definition on the frac arm
        s = s[s["budget_type"] == "frac"]
    frac = s["frac"].min()
    a = s[(s["frac"] == frac) & (s["outcome"] == outcome)]
    return a.groupby("dataset")["delta"].mean()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary", default="results/summary.csv")
    ap.add_argument("--outcome", default="aurc")
    a = ap.parse_args()
    harm = harm_by_dataset(a.summary, a.outcome)
    df = pd.DataFrame([dataset_properties(d) for d in harm.index])
    df["harm"] = df["dataset"].map(harm).astype(float)
    df = df.sort_values("harm", ascending=False).reset_index(drop=True)

    print(f"=== harm = mean {a.outcome} penalty at most-aggressive budget, by dataset ===")
    print(df.to_string(index=False, float_format=lambda v: f"{v:.3f}"))
    print("\n=== Spearman correlation of harm with each dataset property ===")
    rows = []
    for key, label in PROPS:
        rho, pv = spearmanr(df[key], df["harm"])
        rows.append((label, rho, pv))
        print(f"  {label:24s} rho={rho:+.3f}  p={pv:.3f}")
    rows.sort(key=lambda r: -abs(r[1]))
    top_label, top_rho, _ = rows[0]
    top_key = next(k for k, lab in PROPS if lab == top_label)
    direction = "lower" if top_rho > 0 else "higher"
    print(f"\nRULE: reduction is safest when {top_label} is {direction} "
          f"(strongest predictor; Spearman rho={top_rho:+.3f}).")

    # table
    cols = [("dataset", "Dataset"), ("p", "$p$"), ("np_ratio", "$n{:}p$"),
            ("redundancy", "Redund."), ("intrinsic_dim_frac", "Intr.dim"),
            ("prevalence", "Prev."), ("harm", f"{a.outcome.upper()} penalty")]
    lines = ["% auto-generated by experiments/meta_analysis.py from results/summary.csv",
             r"\begin{tabular}{@{}l" + "r" * (len(cols) - 1) + r"@{}}", r"\toprule",
             " & ".join(c[1] for c in cols) + r" \\", r"\midrule"]
    for _, r in df.iterrows():
        cells = [str(r["dataset"])]
        for key, _ in cols[1:]:
            v = r[key]
            cells.append(f"{int(v)}" if key == "p" else f"{v:+.3f}" if key == "harm" else f"{v:.2f}")
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    Path("paper/meta_table.tex").write_text("\n".join(lines) + "\n")

    # two panels: harm vs feature count p (left) and vs the ABSOLUTE retained count at the
    # aggressive budget (right) -- the revision's requalified screen. Markers encode the
    # manuscript's compact (p<=12, filled circles) / wide (p>=16, open squares) classes.
    from nsclinfs.reduction import retained_k
    df["k_min"] = df["p"].apply(lambda p_: retained_k(0.25, int(p_)))
    rho_k, _ = spearmanr(df["k_min"], df["harm"])
    rho_p, _ = spearmanr(df["p"], df["harm"])
    fig, axes = plt.subplots(1, 2, figsize=(8.6, 3.5), sharey=True)
    for ax, key, xlabel, r_ in ((axes[0], "p", "feature count $p$", rho_p),
                                (axes[1], "k_min", "retained $k$ at the 25\\,% budget", rho_k)):
        for wide, marker, face in ((False, "o", "#2c6fbb"), (True, "s", "none")):
            sub_ = df[(df["p"] >= 16) == wide]
            ax.scatter(sub_[key], sub_["harm"], marker=marker, facecolors=face,
                       edgecolors="#2c6fbb", label="wide ($p\\geq16$)" if wide else
                       "compact ($p\\leq12$)")
        xspan = float(df[key].max() - df[key].min())
        for _, r in df.iterrows():
            near_right = r[key] > df[key].min() + 0.78 * xspan
            ax.annotate(r["dataset"], (r[key], r["harm"]), fontsize=6, alpha=0.75,
                        xytext=(-3 if near_right else 3, 3), textcoords="offset points",
                        ha="right" if near_right else "left")
        ax.axhline(0, color="grey", lw=0.6, ls=":")
        ax.margins(x=0.12)
        ax.set_xlabel(xlabel)
        ax.set_title(f"Spearman $\\rho={r_:+.2f}$", fontsize=9)
    axes[0].set_ylabel(f"{a.outcome.upper()} penalty at 25% of features")
    axes[0].legend(fontsize=7, frameon=False)
    fig.tight_layout(); fig.savefig("paper/figures/meta_harm.pdf")
    print("[meta] wrote paper/meta_table.tex + paper/figures/meta_harm.pdf")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
