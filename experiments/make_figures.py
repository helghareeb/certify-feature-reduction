"""Regenerate the manuscript figure and tables FROM the committed summary CSV (never by
re-running experiments). Reads results/summary.csv (the single canonical aggregator output,
R2) and writes, under paper/:
  - figures/reduction_curves.pdf
  - headline_table.tex        (6 outcomes; material split into worse vs better)
  - per_dataset_table.tex     (per dataset x outcome mean delta at the most aggressive budget)
  - silent_cells.tex          (AUROC-silent cell counts per budget, explicit definition)

"AUROC-silent" cell: at a given fraction, a (dataset, method, classifier) cell where at least
one of ECE / Brier / AURC is materially WORSE while AUROC is NOT materially worse -- i.e.
calibration or selective reliability degrades without a discrimination warning.

    PYTHONPATH=src python experiments/make_figures.py
"""
from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

PANELS = [("ece", "Expected calibration error"), ("aurc", "AURC (selective risk)"), ("auroc", "AUROC")]
HEAD = [("auroc", "AUROC", "higher"), ("ece", "ECE", "lower"), ("brier", "Brier", "lower"),
        ("aurc", "AURC", "lower"), ("auroc_gap", "AUROC subgroup gap", "lower"),
        ("ece_gap", "ECE subgroup gap", "lower")]
SILENT_TRIGGERS = ["ece", "brier", "aurc"]


def _load(summary_csv: str) -> pd.DataFrame:
    from nsclinfs.hashing import CALIB_HASH_KEY, assert_single_hash
    df = pd.read_csv(summary_csv, comment="#")
    if CALIB_HASH_KEY in df.columns:                   # R6: refuse a mixed-hash summary
        assert_single_hash(df[CALIB_HASH_KEY])
    if "budget_type" in df.columns:                    # v1-era figures/tables read the frac arm
        df = df[df["budget_type"] == "frac"]
    return df


_DATASET_OUTCOMES = {
    "cleveland": "coronary disease", "pima": "diabetes onset", "ilpd": "liver disease",
    "heartfailure": "death", "wdbc": "malignant", "statlogheart": "coronary disease",
    "haberman": "5-year death", "hepatitis": "death", "mammographic": "malignant",
    "bcw": "malignant", "spectf": "abnormal SPECT", "diabetes130": "30-day readmission",
}


def datasets_table(datasets: list[str], out_tex: str,
                   calib_path: str = "config/calibration.json") -> None:
    """Descriptor table (n, p, prevalence, protected attribute) loaded from the committed
    loaders, under the SAME dataset_params as the grid (so n reflects what actually ran)."""
    import json
    import numpy as np
    from nsclinfs import data as dataload
    dataset_params = json.loads(Path(calib_path).read_text()).get("dataset_params", {})
    lines = ["% auto-generated by experiments/make_figures.py from the dataset loaders",
             r"\begin{tabular}{@{}llrrrl@{}}", r"\toprule",
             r"Dataset & Outcome & $n$ & $p$ & Prev. & Protected \\", r"\midrule"]
    for name in datasets:
        X, y, s = dataload.load(name, params=dataset_params.get(name))
        prot = (s.name if s.nunique() > 1 else "none").replace("_", " ")
        n_tex = f"{len(y):,}".replace(",", r"{,}")     # LaTeX thousands separator
        lines.append(f"{name} & {_DATASET_OUTCOMES.get(name, '--')} & {n_tex} & {X.shape[1]} & "
                     f"{float(np.mean(y)):.3f} & {prot} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    Path(out_tex).write_text("\n".join(lines) + "\n")
    print(f"[figures] wrote {out_tex}")


def figures(df: pd.DataFrame, out_pdf: str) -> None:
    datasets = sorted(df["dataset"].unique())
    fig, axes = plt.subplots(1, len(PANELS), figsize=(4.2 * len(PANELS), 3.9))
    handles, labels = [], []
    for ax, (outcome, label) in zip(axes, PANELS):
        sub = df[df["outcome"] == outcome]
        for ds in datasets:
            d = sub[sub["dataset"] == ds].groupby("frac")["mean"].mean().sort_index()
            if d.notna().any():
                line, = ax.plot(d.index, d.values, marker="o", ms=4, label=ds)
                if ax is axes[0]:
                    handles.append(line)
                    labels.append(ds)
        ax.set_xlabel("fraction of features retained")
        ax.set_ylabel(label)
        ax.invert_xaxis()
        ax.grid(alpha=0.3)
    # single legend below all panels (outside the data area, no overlap)
    fig.legend(handles, labels, loc="lower center", ncol=6, fontsize=8, frameon=False,
               bbox_to_anchor=(0.5, -0.02))
    fig.tight_layout(rect=(0, 0.08, 1, 1))
    Path(out_pdf).parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_pdf, bbox_inches="tight")
    print(f"[figures] wrote {out_pdf}")


def headline_table(df: pd.DataFrame, out_tex: str) -> float:
    frac = df["frac"].min()
    aggr = df[df["frac"] == frac]
    lines = ["% auto-generated by experiments/make_figures.py from results/summary.csv",
             r"\begin{tabular}{@{}lrrr@{}}", r"\toprule",
             r"Outcome & Mean diff.\ vs.\ full & Material worse & Material better \\", r"\midrule"]
    for key, label, direction in HEAD:
        s = aggr[aggr["outcome"] == key]
        if not len(s):
            continue
        delta, n = s["delta"].mean(), int(s["delta"].notna().sum())
        worse, better = int(s["material_worse"].sum()), int(s["material_better"].sum())
        arrow = r"$\uparrow$" if direction == "higher" else r"$\downarrow$"
        gap = " (widened)" if "gap" in key else ""
        lines.append(f"{label} ({arrow} better) & {delta:+.4f} & {worse}/{n}{gap} & {better}/{n} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    Path(out_tex).write_text("\n".join(lines) + "\n")
    print(f"[figures] wrote {out_tex} (most aggressive frac = {frac})")
    return frac


NEW_AXES = [
    ("net_benefit", "Net benefit (DCA)", "higher"),
    ("net_benefit_gap", "Net-benefit parity gap", "lower"),
    ("conformal_efficiency", "Conformal set size", "lower"),
    ("conformal_coverage_gap", "Group coverage gap", "lower"),
    ("selective_ece", "Selective ECE", "lower"),
]


def new_axes_table(df: pd.DataFrame, out_tex: str) -> None:
    """The four new reliability axes (net benefit, conformal coverage/efficiency, selective
    calibration) at the most aggressive budget, direction-resolved."""
    frac = df["frac"].min()
    aggr = df[df["frac"] == frac]
    lines = ["% auto-generated by experiments/make_figures.py from results/summary.csv",
             r"\begin{tabular}{@{}lrrr@{}}", r"\toprule",
             r"Reliability axis & Mean diff.\ vs.\ full & Material worse & Material better \\", r"\midrule"]
    for key, label, direction in NEW_AXES:
        s = aggr[aggr["outcome"] == key]
        if not len(s):
            continue
        delta, n = s["delta"].mean(), int(s["delta"].notna().sum())
        worse, better = int(s["material_worse"].sum()), int(s["material_better"].sum())
        arrow = r"$\uparrow$" if direction == "higher" else r"$\downarrow$"
        lines.append(f"{label} ({arrow} better) & {delta:+.4f} & {worse}/{n} & {better}/{n} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    Path(out_tex).write_text("\n".join(lines) + "\n")
    print(f"[figures] wrote {out_tex}")


def per_dataset_table(df: pd.DataFrame, frac: float, out_tex: str) -> None:
    aggr = df[df["frac"] == frac]
    cols = [("auroc", "AUROC"), ("ece", "ECE"), ("brier", "Brier"), ("aurc", "AURC")]
    lines = ["% auto-generated by experiments/make_figures.py from results/summary.csv",
             r"\begin{tabular}{@{}l" + "r" * len(cols) + r"@{}}", r"\toprule",
             "Dataset & " + " & ".join(c[1] for c in cols) + r" \\", r"\midrule"]
    for ds in sorted(aggr["dataset"].unique()):
        cells = []
        for key, _ in cols:
            s = aggr[(aggr["dataset"] == ds) & (aggr["outcome"] == key)]
            cells.append(f"{s['delta'].mean():+.3f}")
        lines.append(f"{ds} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    Path(out_tex).write_text("\n".join(lines) + "\n")
    print(f"[figures] wrote {out_tex}")


def silent_cells(df: pd.DataFrame, out_tex: str) -> dict:
    """Count AUROC-silent cells per fraction and write a small table. Returns {frac: count}.

    A cell is AUROC-silent when at least one of ECE/Brier/AURC is materially WORSE and AUROC
    is NOT materially worse, computed explicitly per (dataset, method, classifier) cell.
    """
    counts = {}
    fracs = sorted(f for f in df["frac"].unique() if f != 1.0)
    key = ["dataset", "method", "classifier"]
    for frac in fracs:
        sub = df[df["frac"] == frac]
        n_silent = 0
        for _, cell in sub.groupby(key):
            auroc_worse = bool(cell.loc[cell["outcome"] == "auroc", "material_worse"].any())
            calib_worse = bool(cell.loc[cell["outcome"].isin(SILENT_TRIGGERS), "material_worse"].any())
            if calib_worse and not auroc_worse:
                n_silent += 1
        counts[frac] = n_silent
    n_cells = df.groupby(key).ngroups
    lines = ["% auto-generated by experiments/make_figures.py from results/summary.csv",
             "% AUROC-silent: ECE/Brier/AURC materially worse while AUROC is not, per (dataset,method,classifier) cell",
             r"\begin{tabular}{@{}lr@{}}", r"\toprule",
             rf"Fraction of features retained & AUROC-silent cells (of {n_cells}) \\", r"\midrule"]
    for frac in sorted(counts, reverse=True):
        lines.append(f"{frac:g} & {counts[frac]} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    Path(out_tex).write_text("\n".join(lines) + "\n")
    print(f"[figures] wrote {out_tex}; silent counts {counts}")
    return counts


def recalibration_table(recal_csv: str, out_tex: str) -> None:
    """Raw vs.\ Platt vs.\ isotonic recalibrated reduction penalty at the most aggressive budget,
    from the separate leakage-safe recalibration-depth summary."""
    if not Path(recal_csv).exists():
        return
    df = pd.read_csv(recal_csv, comment="#")
    frac = df["frac"].min()
    a = df[df["frac"] == frac]
    rows = [("auroc", "AUROC", r"$\uparrow$"), ("ece", "ECE", r"$\downarrow$"),
            ("brier", "Brier", r"$\downarrow$"), ("aurc", "AURC", r"$\downarrow$"),
            ("net_benefit", "Net benefit", r"$\uparrow$")]
    cals = [("none", "Raw"), ("sigmoid", "Platt"), ("isotonic", "Isotonic")]
    present = [(c, lab) for c, lab in cals if c in a["calibrate"].unique()]
    header = "Outcome & " + " & ".join(f"{lab} penalty (worse)" for _, lab in present) + r" \\"
    # The provenance line names the ACTUAL source rather than a hardcoded filename: the
    # recalibration control has two summaries (the single-ranker original and the all-rankers
    # rebuild), and a table that misnames which one it came from is precisely the drift R2
    # exists to prevent.
    lines = [f"% auto-generated by experiments/make_figures.py from {recal_csv}",
             r"\begin{tabular}{@{}l" + "r" * len(present) + r"@{}}", r"\toprule", header, r"\midrule"]
    for key, label, arrow in rows:
        cells = []
        for cal, _ in present:
            s = a[(a["calibrate"] == cal) & (a["outcome"] == key)]
            cells.append(f"{s['delta'].mean():+.4f} ({int(s['material_worse'].sum())}/{len(s)})"
                         if len(s) else "--")
        if all(c == "--" for c in cells):
            continue
        lines.append(f"{label} ({arrow}) & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    Path(out_tex).write_text("\n".join(lines) + "\n")
    print(f"[figures] wrote {out_tex}")


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--summary", default="results/summary.csv")
    p.add_argument("--pdf", default="paper/figures/reduction_curves.pdf")
    p.add_argument("--tex", default="paper/headline_table.tex")
    # Defaults to the single-ranker control that Section 4.8 currently reports. Point it at
    # results/summary_recalibration_allrankers.csv once that burn lands, which is what removes
    # the single-ranker limitation the section states.
    p.add_argument("--recal", default="results/summary_recalibration.csv")
    a = p.parse_args()
    df = _load(a.summary)
    figures(df, a.pdf)
    frac = headline_table(df, a.tex)
    datasets_table(sorted(df["dataset"].unique()), "paper/datasets_table.tex")
    per_dataset_table(df, frac, "paper/per_dataset_table.tex")
    silent_cells(df, "paper/silent_cells.tex")
    new_axes_table(df, "paper/new_axes_table.tex")
    recalibration_table(a.recal, "paper/recalibration_table.tex")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
