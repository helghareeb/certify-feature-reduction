"""R1.3: the worked patient-level decision-flip example, from committed caches only.

Reads config/analysis.json (the a-priori cell + threshold), the persisted out-of-fold
probability caches (results/cache/poof/), and the per-threshold net-benefit curve cache
(results/cache/nb_curves.parquet). Produces:

  paper/worked_example_table.tex   exemplar patients: features, mean p_full, mean p_reduced,
                                   decisions at t, flip rate over the 30 paired repetitions
  paper/figures/decision_curve_worked.pdf
                                   per-threshold NB, full vs reduced vs treat-all/none,
                                   vertical line at the clinical threshold
  results/worked_example.json      every number the manuscript quotes for R1.3, both cells

No model is fit here (R1/R2: presentation over committed artifacts). Patients are fixed
across repetitions -- reps vary only the CV split -- so per-patient aggregation over reps
is well-defined; a patient's "flip rate" is the fraction of the 30 paired models in which
reduction moves them across the treatment threshold.

    PYTHONPATH=src python experiments/worked_example.py
"""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from nsclinfs import data as dataload
from nsclinfs.hashing import CALIB_HASH_KEY, assert_single_hash

ROOT = Path(__file__).resolve().parents[1]


def load_poof(cell: dict, dataset: str) -> pd.DataFrame:
    name = "__".join([dataset, cell["method"], cell["classifier"], cell["calibrate"]])
    files = sorted((ROOT / "results/cache/poof").glob(f"{name}__rep*.parquet"))
    if not files:
        raise SystemExit(f"no p_oof cache for {name} -- was persist.p_oof_cells configured?")
    reps = []
    for f in files:
        df = pd.read_parquet(f)
        df["rep"] = int(f.stem.rsplit("rep", 1)[1])
        reps.append(df)
    return pd.concat(reps)


def flips(poof: pd.DataFrame, full: str, red: str, t: float) -> pd.DataFrame:
    d = poof.reset_index(names="patient")
    d["treat_full"] = d[full] >= t
    d["treat_red"] = d[red] >= t
    d["flip"] = d["treat_full"] != d["treat_red"]
    g = d.groupby("patient").agg(y=("y", "first"), sensitive=("sensitive", "first"),
                                 p_full=(full, "mean"), p_red=(red, "mean"),
                                 flip_rate=("flip", "mean"),
                                 to_no_treat=("treat_red", lambda s: 1 - s.mean()))
    g["treat_full_mean"] = d.groupby("patient")["treat_full"].mean()
    return g


def main() -> int:
    cfg = json.loads((ROOT / "config/analysis.json").read_text())
    out: dict = {}
    nb_cache = pd.read_parquet(ROOT / "results/cache/nb_curves.parquet")
    assert_single_hash(nb_cache[CALIB_HASH_KEY])

    for key in ("worked_example", "secondary_example"):
        c = cfg[key]
        ds, cell, t = c["dataset"], c["cell"], float(c["threshold"])
        full, red = c["budget_full"], c["budget_reduced"]
        poof = load_poof(cell, ds)
        g = flips(poof, full, red, t)
        n_pat = len(g)
        stats = {
            "dataset": ds, "threshold": t, "n_patients": n_pat,
            "n_flip_majority": int((g["flip_rate"] >= 0.5).sum()),
            "n_flip_ever": int((g["flip_rate"] > 0).sum()),
            "n_flip_majority_y1": int(((g["flip_rate"] >= 0.5) & (g["y"] == 1)).sum()),
            "n_missed_treatment": int(((g["flip_rate"] >= 0.5) & (g["y"] == 1)
                                       & (g["p_full"] >= t) & (g["p_red"] < t)).sum()),
            "sensitivity": {},
        }
        for ts in c.get("sensitivity_thresholds", []):
            gs = flips(poof, full, red, float(ts))
            stats["sensitivity"][str(ts)] = {
                "n_flip_majority": int((gs["flip_rate"] >= 0.5).sum()),
                "n_flip_majority_y1": int(((gs["flip_rate"] >= 0.5) & (gs["y"] == 1)).sum())}
        out[key] = stats

        if key == "worked_example":
            # exemplar table: prioritise true positives pushed below the threshold (missed
            # treatment), then the largest flip rates
            X, y, sens = dataload.load(ds)
            missed = g[(g["y"] == 1) & (g["p_full"] >= t) & (g["p_red"] < t)]
            rest = g.drop(missed.index)
            pick = pd.concat([missed.sort_values("flip_rate", ascending=False),
                              rest.sort_values("flip_rate", ascending=False)]
                             ).head(int(cfg["worked_example"].get("n_exemplar_patients", 8)))
            feat_cols = list(X.columns)
            lines = ["% auto-generated by experiments/worked_example.py from committed caches",
                     r"\begin{tabular}{@{}r" + "r" * len(feat_cols) + r"crrccr@{}}", r"\toprule",
                     "Pt. & " + " & ".join(c.replace("_", r"\_") for c in feat_cols)
                     + r" & $y$ & $\bar p_{\mathrm{full}}$ & $\bar p_{k=1}$ & "
                     + f"treat@{t:g} (full) & treat@{t:g} (reduced) & flip rate" + r" \\",
                     r"\midrule"]
            for pid, r in pick.iterrows():
                fv = " & ".join("--" if pd.isna(v) else f"{v:g}" for v in X.iloc[int(pid)][feat_cols])
                lines.append(f"{int(pid)} & {fv} & {int(r['y'])} & {r['p_full']:.3f} & "
                             f"{r['p_red']:.3f} & {'yes' if r['p_full'] >= t else 'no'} & "
                             f"{'yes' if r['p_red'] >= t else 'no'} & {r['flip_rate']:.2f} \\\\")
            lines += [r"\bottomrule", r"\end{tabular}"]
            (ROOT / "paper/worked_example_table.tex").write_text("\n".join(lines) + "\n")

            # decision curve at per-threshold resolution, from the committed NB cache
            nb = nb_cache[(nb_cache["dataset"] == ds)
                          & (nb_cache["method"] == cell["method"])
                          & (nb_cache["classifier"] == cell["classifier"])
                          & (nb_cache["calibrate"] == cell["calibrate"])]
            prev = float(g["y"].mean())
            fig, ax = plt.subplots(figsize=(4.8, 3.5))
            for budget, label, style in ((full, "full features", "-"),
                                         (red, "25\\,% budget ($k{=}1$)", "--")):
                cur = nb[nb["budget"] == budget].groupby("t")["nb"].mean().sort_index()
                ax.plot(cur.index, cur.values, style, label=label)
            ts_ = np.linspace(0.01, 0.5, 200)
            ax.plot(ts_, prev - (1 - prev) * ts_ / (1 - ts_), ":", color="grey", label="treat all")
            ax.axhline(0, color="grey", lw=0.6)
            ax.axvline(t, color="red", lw=0.8, alpha=0.6)
            ax.annotate(f"t={t:g}", (t, ax.get_ylim()[1] * 0.9), color="red", fontsize=8)
            ax.set_xlabel("threshold probability $t$")
            ax.set_ylabel("net benefit")
            ax.set_ylim(bottom=-0.05)
            ax.legend(fontsize=8, frameon=False)
            fig.tight_layout()
            fig.savefig(ROOT / "paper/figures/decision_curve_worked.pdf")
            print(f"[worked] table + figure written; {stats['n_flip_majority']} of {n_pat} "
                  f"patients flip in the majority of repetitions at t={t:g}")

    # -- Enrichment #3: population-scale flip-rate distribution (both cells) -----------
    fig, ax = plt.subplots(figsize=(4.8, 3.3))
    for key, style in (("worked_example", "-"), ("secondary_example", "--")):
        c = cfg[key]
        g = flips(load_poof(c["cell"], c["dataset"]), c["budget_full"], c["budget_reduced"],
                  float(c["threshold"]))
        fr = np.sort(g["flip_rate"].to_numpy())
        ax.plot(fr, np.arange(1, len(fr) + 1) / len(fr), style,
                label=f"{c['dataset']} (n={len(fr):,}, t={c['threshold']:g})")
        out[key]["flip_rate_deciles"] = {str(q): round(float(np.quantile(fr, q)), 4)
                                         for q in (0.5, 0.9, 0.95, 0.99)}
    ax.set_xlabel("per-patient decision-flip rate over the 30 paired repetitions")
    ax.set_ylabel("cumulative fraction of patients")
    ax.legend(fontsize=8, frameon=False)
    ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(ROOT / "paper/figures/flip_rate_distribution.pdf")

    # -- Enrichment #4: who bears the flips -- race split on the full cohort -----------
    c = cfg["secondary_example"]
    g = flips(load_poof(c["cell"], c["dataset"]), c["budget_full"], c["budget_reduced"],
              float(c["threshold"]))
    grp = g.groupby("sensitive").agg(n=("flip_rate", "size"),
                                     mean_flip_rate=("flip_rate", "mean"),
                                     pct_flip_majority=("flip_rate", lambda s: (s >= 0.5).mean()))
    grp = grp.sort_values("mean_flip_rate", ascending=False)
    out["flips_by_race"] = {str(i): {"n": int(r["n"]),
                                     "mean_flip_rate": round(float(r["mean_flip_rate"]), 4),
                                     "pct_flip_majority": round(float(r["pct_flip_majority"]), 4)}
                            for i, r in grp.iterrows()}
    lines = ["% auto-generated by experiments/worked_example.py from committed caches",
             r"\begin{tabular}{@{}lrrr@{}}", r"\toprule",
             r"Race group & $n$ & mean flip rate & \% flipped in majority of reps \\", r"\midrule"]
    for grp_name, r in grp.iterrows():
        n_tex = f"{int(r['n']):,}".replace(",", r"{,}")
        lines.append(f"{str(grp_name).replace('_', ' ')} & {n_tex} & "
                     f"{r['mean_flip_rate']:.4f} & {100 * r['pct_flip_majority']:.2f}\\,\\% \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (ROOT / "paper/flip_by_race_table.tex").write_text("\n".join(lines) + "\n")

    # -- Enrichment #5: reliability diagrams, full vs reduced (primary cell) -----------
    c = cfg["worked_example"]
    poof = load_poof(c["cell"], c["dataset"])
    fig, axes = plt.subplots(1, 2, figsize=(7.6, 3.4), sharey=True)
    bins = np.linspace(0, 1, 16)
    for ax, budget, title in ((axes[0], c["budget_full"], "full features"),
                              (axes[1], c["budget_reduced"], "25\\,% budget")):
        centers, observed, counts = [], [], []
        pv, yv = poof[budget].to_numpy(), poof["y"].to_numpy()
        for lo, hi in zip(bins[:-1], bins[1:]):
            m = (pv >= lo) & (pv < hi) if hi < 1 else (pv >= lo) & (pv <= hi)
            if m.sum() >= 30:                      # pooled over reps; sparse bins suppressed
                centers.append(pv[m].mean()); observed.append(yv[m].mean()); counts.append(m.sum())
        ax.plot([0, 1], [0, 1], ":", color="grey", lw=0.8)
        ax.plot(centers, observed, "o-", ms=3)
        ax.set_xlabel("predicted probability"); ax.set_title(title, fontsize=9)
    axes[0].set_ylabel("observed event frequency")
    fig.tight_layout()
    fig.savefig(ROOT / "paper/figures/reliability_worked.pdf")

    (ROOT / "results/worked_example.json").write_text(json.dumps(out, indent=2) + "\n")
    print(json.dumps(out, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
