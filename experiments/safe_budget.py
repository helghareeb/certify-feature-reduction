"""Enrichment #1: the minimum certified-safe feature budget per dataset.

Turns the audit from a warning into an instrument: for each dataset, the smallest retained
count k at which NO (ranker, learner) cell is materially worse than the full-feature model
on ANY reliability axis. Both budget arms are used (fractional and exact-k mapped to their
realised k), so the frontier is probed at every k the grid visited. The certification rule
is deliberately conservative: one materially-worse cell on one axis at a budget disqualifies
that budget for the dataset.

Emits paper/safe_budget_table.tex + results/safe_budget.json.

    PYTHONPATH=src python experiments/safe_budget.py [--summary results/summary.csv]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

from nsclinfs.hashing import CALIB_HASH_KEY, assert_single_hash

ROOT = Path(__file__).resolve().parents[1]
AXES = ["aurc", "net_benefit", "brier", "ece", "auroc", "conformal_efficiency"]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary", default="results/summary.csv")
    a = ap.parse_args()
    s = pd.read_csv(ROOT / a.summary, comment="#")
    assert_single_hash(s[CALIB_HASH_KEY])
    if "k_features" not in s.columns:
        raise SystemExit("summary lacks k_features -- run on the v2 aggregate")
    s = s[(s["calibrate"] == "none") & s["outcome"].isin(AXES)]

    rows, out = [], {}
    for ds, g in s.groupby("dataset"):
        p = int(g["n_features"].iloc[0])
        ref_k = p
        by_k = {}
        for k, gk in g[g["k_features"] < ref_k].groupby("k_features"):
            n_worse = int(gk["material_worse"].sum())
            by_k[int(k)] = {"n_material_worse_cells": n_worse,
                            "n_cells_axes": int(len(gk)),
                            "certified_safe": n_worse == 0}
        safe_ks = [k for k, v in by_k.items() if v["certified_safe"]]
        # the frontier: the smallest k that is safe AND below which nothing is safe again
        # (report the smallest safe k, plus whether safety is monotone in k)
        k_min_safe = min(safe_ks) if safe_ks else None
        monotone = all(k >= (k_min_safe or 0) for k in safe_ks) if safe_ks else True
        out[ds] = {"p": p, "budgets_probed_k": sorted(by_k), "by_k": by_k,
                   "k_min_safe": k_min_safe, "safety_monotone_in_k": monotone}
        rows.append({"dataset": ds, "p": p,
                     "k_min_safe": k_min_safe if k_min_safe is not None else float("nan"),
                     "frac_equiv": (k_min_safe / p) if k_min_safe else float("nan"),
                     "none_safe": k_min_safe is None})

    df = pd.DataFrame(rows).sort_values(["none_safe", "frac_equiv"],
                                        ascending=[True, True]).reset_index(drop=True)
    lines = ["% auto-generated by experiments/safe_budget.py",
             r"\begin{tabular}{@{}lrrr@{}}", r"\toprule",
             r"Dataset & $p$ & smallest certified-safe $k$ & as fraction of $p$ \\", r"\midrule"]
    for _, r in df.iterrows():
        if r["none_safe"]:
            lines.append(f"{r['dataset']} & {int(r['p'])} & "
                         r"\emph{none below full} & --- \\")
        else:
            lines.append(f"{r['dataset']} & {int(r['p'])} & {int(r['k_min_safe'])} & "
                         f"{r['frac_equiv']:.2f} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (ROOT / "paper/safe_budget_table.tex").write_text("\n".join(lines) + "\n")
    (ROOT / "results/safe_budget.json").write_text(json.dumps(out, indent=2) + "\n")
    print(df.to_string(index=False))
    non_mono = [d for d, v in out.items() if not v["safety_monotone_in_k"]]
    if non_mono:
        print(f"NOTE: safety is NOT monotone in k for {non_mono} -- report per-k detail there.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
