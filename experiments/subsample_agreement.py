"""R1.4 robustness arm: did the v1 subsample mislead? Full-cohort vs n=6000 agreement.

Compares the Diabetes-130 rows of the v2 full-cohort summary (results/summary.csv) against
the corrected-stratification n=6000 robustness run (results/summary_subcheck.csv). The two
files carry DIFFERENT calibration hashes by design (two configs); each is hash-checked
internally, and this script is the one sanctioned place they meet (R2: it emits the single
canonical agreement table).

Emits paper/diabetes_full_table.tex + results/subsample_agreement.json: per
(ranker, learner) the paired delta at the most aggressive budget under full vs 6k for the
headline outcomes, whether the CIs overlap, whether the sign agrees, and whether the
materiality verdict agrees.

    PYTHONPATH=src python experiments/subsample_agreement.py
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from nsclinfs.hashing import CALIB_HASH_KEY, assert_single_hash

ROOT = Path(__file__).resolve().parents[1]
OUTCOMES = ["aurc", "auroc", "net_benefit", "ece", "brier"]


def load(path: Path) -> pd.DataFrame:
    df = pd.read_csv(path, comment="#")
    assert_single_hash(df[CALIB_HASH_KEY])
    df = df[(df["dataset"] == "diabetes130") & (df["calibrate"] == "none")]
    if "budget_type" in df.columns:
        df = df[df["budget_type"] == "frac"]
    return df[df["frac"] == df["frac"].min()]


def main() -> int:
    full = load(ROOT / "results/summary.csv")
    sub = load(ROOT / "results/summary_subcheck.csv")
    key = ["method", "classifier", "outcome"]
    m = (full.merge(sub, on=key, suffixes=("_full", "_6k"))
             .query("outcome in @OUTCOMES").sort_values(key))
    m["ci_overlap"] = ~((m["diff_ci_lo_full"] > m["diff_ci_hi_6k"])
                        | (m["diff_ci_lo_6k"] > m["diff_ci_hi_full"]))
    m["sign_agree"] = (m["delta_full"] * m["delta_6k"] >= 0)
    m["verdict_agree"] = (m["material_worse_full"] == m["material_worse_6k"])

    gap = (m["delta_full"] - m["delta_6k"]).abs()
    # Direction of the verdict disagreements -- the full cohort resolving an effect the
    # subsample was underpowered to see, versus the subsample asserting one the full
    # cohort refutes -- and the sign-reversal count. Section 4.9 quotes both, so they are
    # emitted here rather than recounted by hand from the table.
    disagree = m[~m["verdict_agree"]]
    rev = m[~m["sign_agree"]]
    biggest = rev.loc[gap[rev.index].idxmax()]
    summary = {
        "n_comparisons": int(len(m)),
        "ci_overlap": int(m["ci_overlap"].sum()),
        "sign_agree": int(m["sign_agree"].sum()),
        "sign_reversals": int(len(rev)),
        "verdict_agree": int(m["verdict_agree"].sum()),
        "verdict_full_only_material": int(disagree["material_worse_full"].sum()),
        "verdict_6k_only_material": int(disagree["material_worse_6k"].sum()),
        "max_abs_delta_gap": round(float(gap.max()), 4),
        "median_abs_delta_gap": round(float(gap.median()), 4),
        "largest_sign_reversal": {
            "method": str(biggest["method"]), "classifier": str(biggest["classifier"]),
            "outcome": str(biggest["outcome"]),
            "delta_full": round(float(biggest["delta_full"]), 4),
            "delta_6k": round(float(biggest["delta_6k"]), 4),
        },
    }
    (ROOT / "results/subsample_agreement.json").write_text(
        json.dumps(summary, indent=2) + "\n")

    lines = ["% auto-generated by experiments/subsample_agreement.py",
             r"\begin{tabular}{@{}llrrrccc@{}}", r"\toprule",
             r"Ranker & Learner & Outcome & $\Delta$ (full $n$) & $\Delta$ ($n{=}6000$) & "
             r"CIs overlap & sign & verdict \\", r"\midrule"]
    for _, r in m.iterrows():
        lines.append(
            f"{r['method'].replace('_', chr(92) + '_')} & {r['classifier']} & "
            f"{r['outcome'].replace('_', chr(92) + '_')} & {r['delta_full']:+.4f} & "
            f"{r['delta_6k']:+.4f} & {'yes' if r['ci_overlap'] else 'NO'} & "
            f"{'agree' if r['sign_agree'] else 'DISAGREE'} & "
            f"{'agree' if r['verdict_agree'] else 'DISAGREE'} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (ROOT / "paper/diabetes_full_table.tex").write_text("\n".join(lines) + "\n")
    print(json.dumps(summary, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
